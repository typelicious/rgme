// Compiles src/wasm/reference-core.wat -> src/wasm/reference-core.ts (base64). Dev-time only (needs wabt).
// Usage: node packages/core/scripts/build-reference-core.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import wabtInit from "wabt";

const dir = fileURLToPath(new URL("../src/wasm/", import.meta.url));
const wat = readFileSync(dir + "reference-core.wat", "utf8");
const wabt = await wabtInit();
const mod = wabt.parseWat("reference-core.wat", wat);
mod.validate();
const bytes = Buffer.from(mod.toBinary({ log: false, write_debug_names: false }).buffer);
const out = `// GENERATED by packages/core/scripts/build-reference-core.mjs from reference-core.wat — do not edit.
// TIMING / INTEGRATION REFERENCE ONLY: not an Amiga emulator (see reference-core.wat header).
export const REFERENCE_CORE_WASM_BASE64 =
  "${bytes.toString("base64")}";
export const REFERENCE_CORE_WASM_SHA256 = "${createHash("sha256").update(bytes).digest("hex")}";
`;
writeFileSync(dir + "reference-core.ts", out);
console.log(`reference-core.ts written (${bytes.length} bytes)`);
