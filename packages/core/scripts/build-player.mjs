// Bundles src/export/player-entry.ts into src/export/player-bundle.generated.ts (minified JS as a string).
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

export async function buildPlayerSource() {
  const res = await build({
    entryPoints: [`${root}src/export/player-entry.ts`],
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2020",
    platform: "browser",
    write: false,
    legalComments: "none",
    logLevel: "silent"
  });
  const js = res.outputFiles[0].text;
  return `// GENERATED by scripts/build-player.mjs — do not edit. Run: pnpm --filter @rgme/core build:player\nexport const PLAYER_JS = ${JSON.stringify(js)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(`${root}src/export/player-bundle.generated.ts`, await buildPlayerSource());
  console.log("player bundle written");
}
