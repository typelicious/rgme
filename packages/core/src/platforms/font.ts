const GLYPHS = new Map<string, string[]>(Object.entries(G).map(([k, v]) => [k, v.split("|")]));

export function glyphRows(ch: string): string[] {
  return GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get("?box")!;
}

/** Draws text at (x,y) with 6px advance * scale and 7px glyph height * scale. Returns the pixel width drawn. */
export function drawText(ctx: Canvas2DLike, text: string, x: number, y: number, color: string, scale = 1): number {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const rows = glyphRows(ch);
    for (let r = 0; r < rows.length; r++) {
      const row = rows[r]!;
      let c = 0;
      while (c < row.length) {
        if (row[c] !== "#") { c++; continue; }
        let run = c;
        while (run < row.length && row[run] === "#") run++;
        ctx.fillRect(cx + c * scale, y + r * scale, (run - c) * scale, scale); // horizontal runs: fewer rects
        c = run;
      }
    }
    cx += 6 * scale;
  }
  return cx - x;
}

